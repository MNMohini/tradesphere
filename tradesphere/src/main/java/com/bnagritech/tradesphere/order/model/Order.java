package com.bnagritech.tradesphere.order.model;

import com.bnagritech.tradesphere.common.enums.OrderStatus;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.annotation.Version;
import org.springframework.data.mongodb.core.geo.GeoJsonPoint;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.CompoundIndexes;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
@Document(collection = "orders")
@CompoundIndexes({
        @CompoundIndex(name = "user_date",   def = "{'createdBy': 1, 'orderDate': -1}"),
        @CompoundIndex(name = "outlet_date", def = "{'outletId': 1, 'orderDate': -1}"),
        @CompoundIndex(name = "path_date",   def = "{'userPath': 1, 'orderDate': -1}"),
        @CompoundIndex(name = "status_date", def = "{'status': 1, 'orderDate': -1}")
})
public class Order {

    @Id
    private String id;

    // Optimistic locking: stops two users overwriting each other's update
    @Version
    private Long version;

    // ---- Identity ----
    @Indexed(unique = true)
    private String orderNumber;

    // UUID generated by the mobile app; prevents duplicate orders on retry
    @Indexed(unique = true, sparse = true)
    private String clientOrderId;

    // ---- Who, where, when ----
    private String outletId;
    private String outletName;          // snapshot at order time
    private String visitId;
    private String beatId;
    private String territoryId;

    private String createdBy;           // user id
    private String createdByName;       // snapshot at order time
    private List<String> userPath;      // creator's ancestors, for manager-level reports

    private Instant orderDate;
    private GeoJsonPoint location;      // where the order was captured

    // ---- Items and amounts ----
    @Builder.Default
    private List<OrderItems> items = new ArrayList<>();

    private BigDecimal subtotal;
    private BigDecimal totalDiscount;
    private BigDecimal totalSchemeDiscount;
    private BigDecimal totalTax;
    private BigDecimal grandTotal;

    // ---- Status ----
    private OrderStatus status;
    private String cancellationReason;
    private Instant cancelledAt;
    private String remarks;

    @Builder.Default
    private List<OrderStatusHistory> statusHistory = new ArrayList<>();

    // ---- Embedded details ----
    private PaymentInfo payment;
    private DeliveryInfo delivery;

    // ---- Audit ----
    @CreatedDate
    private Instant createdAt;

    @LastModifiedDate
    private Instant updatedAt;

    private String updatedBy;

    // Computed, not stored (Spring Data persists fields only)
    public BigDecimal getPendingAmount() {
        if (grandTotal == null) {
            return BigDecimal.ZERO;
        }
        BigDecimal paid = (payment != null && payment.getPaidAmount() != null)
                ? payment.getPaidAmount()
                : BigDecimal.ZERO;
        return grandTotal.subtract(paid);
    }
}