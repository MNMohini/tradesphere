package com.bnagritech.tradesphere.order.dto;

import com.bnagritech.tradesphere.common.enums.PaymentMode;
import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;

/**
 * Sent by the mobile app / web panel to create an order.
 * Deliberately NOT included (the server sets these): id, orderNumber, status,
 * createdBy, userPath, all amounts and totals, timestamps.
 */
@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
public class CreateOrderRequest {

    // UUID generated by the app; the server uses it to ignore duplicate retries
    @NotBlank(message = "clientOrderId is required")
    @Size(max = 64)
    private String clientOrderId;

    @NotBlank(message = "outletId is required")
    private String outletId;

    private String visitId;
    private String beatId;

    // When the rep took the order on the device (important for offline orders).
    // If null, the server uses the current time.
    private Instant orderDate;

    @Valid
    private LocationDto location;

    @NotEmpty(message = "At least one item is required")
    @Valid
    private List<OrderItemRequest> items;

    // The total the rep saw on screen. The server never uses it for billing;
    // it only compares it with its own total and flags a price change.
    @DecimalMin(value = "0.00")
    private BigDecimal expectedGrandTotal;

    // Payment collected at the time of order (optional)
    private PaymentMode paymentMode;

    @DecimalMin(value = "0.00", message = "paidAmount cannot be negative")
    private BigDecimal paidAmount;

    private String paymentReference;

    // Delivery
    @Size(max = 500)
    private String deliveryAddress;
    private LocalDate expectedDeliveryDate;

    @Size(max = 500)
    private String remarks;

    // true = keep the order as DRAFT (editable); false = submit it straight away
    private boolean saveAsDraft;

}