package com.bnagritech.tradesphere.outlet.model;

import com.bnagritech.tradesphere.common.enums.OutletGrade;
import com.bnagritech.tradesphere.common.enums.OutletStatus;
import com.bnagritech.tradesphere.common.enums.OutletType;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.annotation.Version;
import org.springframework.data.mongodb.core.geo.GeoJsonPoint;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.CompoundIndexes;
import org.springframework.data.mongodb.core.index.GeoSpatialIndexType;
import org.springframework.data.mongodb.core.index.GeoSpatialIndexed;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
@Document(collection = "outlets")
@CompoundIndexes({
        @CompoundIndex(name = "status_name",    def = "{'status': 1, 'name': 1}"),
        @CompoundIndex(name = "beat_status",    def = "{'beatId': 1, 'status': 1}"),
        @CompoundIndex(name = "territory_status", def = "{'territoryId': 1, 'status': 1}"),
        @CompoundIndex(name = "path_status",    def = "{'userPath': 1, 'status': 1}")
})
public class Outlet {

    @Id
    private String id;

    @Version
    private Long version;

    // ---- Codes ----
    // Generated by the server, e.g. OUT-000123
    @Indexed(unique = true)
    private String outletCode;

    // Code from your ERP or the distributor, if you have one
    @Indexed(unique = true, sparse = true)
    private String externalCode;

    // UUID from the mobile app, so a retried "create outlet" never makes a second outlet
    @Indexed(unique = true, sparse = true)
    private String clientOutletId;

    // ---- Details ----
    private String name;
    private String ownerName;
    private String phoneNumber;
    private String alternatePhoneNumber;
    private String email;
    private String gstNumber;
    private OutletType type;
    private OutletGrade grade;

    private OutletAddress address;

    // ---- Location (2dsphere index for nearby searches) ----
    @GeoSpatialIndexed(type = GeoSpatialIndexType.GEO_2DSPHERE)
    private GeoJsonPoint location;
    private Double locationAccuracyMeters;

    // ---- Business mapping (ids only; those modules own the details) ----
    private String territoryId;
    private String beatId;
    private String distributorId;

    // ---- Status ----
    private OutletStatus status;
    private String statusReason;       // why it was rejected or deactivated

    @Builder.Default
    private List<OutletStatusHistory> statusHistory = new ArrayList<>();

    // ---- Who created it ----
    private String createdBy;
    private String createdByName;
    private List<String> userPath;     // creator's ancestors, so their managers can see and approve it

    // ---- Audit ----
    @CreatedDate
    private Instant createdAt;

    @LastModifiedDate
    private Instant updatedAt;

    private String updatedBy;
}

